function res = build_result(fleet, fit, attr, dem, alloc, Z, qty, cost, budget, ing, conv, targets, tgt_cost)
%BUILD_RESULT  Assemble the structured analysis result.
%
%   This struct is the CONTRACT between the numeric pipeline and the
%   narrative layer in ../python. The rule enforced downstream is simple
%   and absolute: a number may appear in generated prose only if it
%   appears as a field here. Anything else is a hallucination, and
%   python/explain_layer/provenance.py fails the build on it.
%
%   The interval and percentile LEVELS (90, 95) are fields here for the
%   same reason as every other number. They were previously absent, and
%   the phrase "90% interval" passed the provenance check only because
%   some unrelated field happened to hold the value 90 that day. A number
%   that validates by coincidence is not validated. If the prose needs a
%   figure, the pipeline gives it a field.
%
%   That is why values are stored pre-rounded to the precision they will
%   be quoted at. Leaving rounding to the language model would make the
%   check unenforceable -- the validator could no longer distinguish a
%   legitimately rounded figure from an invented one.

    N = fleet.n_parts;

    res = struct();

    res.meta = struct( ...
        'n_parts',        N, ...
        'n_units',        numel(fleet.t), ...
        'n_aircraft',     Z, ...
        'n_failures',     sum(~fleet.censored), ...
        'censored_pct',   round_to(100 * mean(fleet.censored)), ...
        'obs_horizon_hr', fleet.horizon, ...
        'plan_horizon_hr', dem.horizon, ...
        'parts_with_le1_failure', sum(fleet.n_failures <= 1), ...
        'records_in',        ing.n_in, ...
        'records_accepted',  ing.n_accepted, ...
        'records_quarantined', ing.n_quarantined, ...
        'quarantine_rate_pct', round_to(100 * ing.quarantine_rate, 1), ...
        'records_reclassified', ing.n_reclassified, ...
        'records_still_on_wing', ing.n_censored_open, ...
        'hardened_failure_count', ing.hardened_failure_count, ...
        'naive_failure_count',    ing.naive_failure_count, ...
        'truth_failure_count',    ing.truth_failure_count, ...
        'hardened_error_pct',     ing.hardened_error_pct, ...
        'naive_error_pct',        ing.naive_error_pct);

    res.model = struct( ...
        'shape_k',      round_to(mean(fit.pooled.k), 2), ...
        'shape_k_lo90', round_to(pctile(fit.pooled.k, 0.05), 2), ...
        'shape_k_hi90', round_to(pctile(fit.pooled.k, 0.95), 2), ...
        'rhat_max',     round_to(conv.rhat_max, 3), ...
        'rhat_all_finite', conv.all_finite, ...
        'rhat_threshold', 1.05, ...
        'interval_pct', 90, ...
        'n_posterior_draws', numel(fit.pooled.k), ...
        'n_chains',     fit.opts.n_chains, ...
        'converged',    conv.pass);

    parts = cell(N, 1);
    for i = 1:N
        if attr.has_own(i), own = round_to(attr.lambda_own(i));
        else,               own = -1; end       % -1 encodes "no standalone estimate"
        parts{i} = struct( ...
            'id',                i, ...
            'units_installed',   attr.n_units(i), ...
            'qty_per_aircraft',  qty(i), ...
            'failures_observed', attr.n_failures(i), ...
            'unit_cost_usd',     cost(i), ...
            'lambda_own_hr',     own, ...
            'lambda_post_hr',    round_to(attr.lambda_post(i)), ...
            'lambda_lo90_hr',    round_to(attr.lambda_lo90(i)), ...
            'lambda_hi90_hr',    round_to(attr.lambda_hi90(i)), ...
            'family_weight_pct', round_to(100 * attr.family_weight(i)), ...
            'demand_mean',       round_to(dem.mean(i), 1), ...
            'demand_p95',        round_to(dem.p95(i)), ...
            'epistemic_share_pct', round_to(100 * dem.epistemic_share(i)), ...
            'stock_bought',      alloc.stock(i), ...
            'expected_backorders', round_to(alloc.ebo(i), 3));
    end
    res.parts = parts;

    res.fleet = struct( ...
        'demand_total_mean',   round_to(sum(dem.mean), 1), ...
        'demand_total_p95',    round_to(sum(dem.p95)), ...
        'demand_percentile',   95, ...
        'epistemic_share_median_pct', round_to(100 * median(dem.epistemic_share)), ...
        'budget_usd',          budget, ...
        'spent_usd',           round_to(alloc.total_cost), ...
        'units_bought',        sum(alloc.stock), ...
        'unspent_usd',         round_to(alloc.unspent), ...
        'availability_before', round_to(alloc.availability_zero, 3), ...
        'availability_after',  round_to(alloc.availability, 3), ...
        'availability_gain_pts', round_to(100 * (alloc.availability - alloc.availability_zero), 1), ...
        'stock_cap_reached',   alloc.at_stock_cap, ...
        'target_availability', targets(end), ...
        'target_cost_usd',     round_to(tgt_cost(end)));

    n_show = min(8, numel(alloc.trace));
    buys = cell(n_show, 1);
    for s = 1:n_show
        tr = alloc.trace(s);
        buys{s} = struct( ...
            'rank',            tr.step, ...
            'part_id',         tr.part, ...
            'unit_cost_usd',   tr.unit_cost, ...
            'backorders_removed', round_to(tr.dEBO, 3), ...
            'per_dollar',      round_to(tr.dEBO_per_dollar, 6), ...
            'availability_after', round_to(tr.availability, 3));
    end
    res.top_buys = buys;
end
